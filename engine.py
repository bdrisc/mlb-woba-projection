"""Run the published 2027 wOBA scenarios in Python with the frozen model export."""
import argparse
import json
import math
import re
from pathlib import Path

SHAPE = ("groundball", "cache_ld_pp", "cache_fb_pp", "cache_pu_pp")
SPRAY = ("pull_pp", "center_pp", "oppo_pp", "spray_other_pp")
SHORT_HISTORY = re.compile(r"^(bat_speed|swing_length|attack_angle|swing_tilt|depth_in_box|off_plate|feet_apart|stance_angle)")
DATA_PATH = Path(__file__).with_name("hitter_what_if_app_data.json")


def finite(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def clip(value, lo, hi):
    return max(lo, min(hi, value))


def predict(model, row):
    """Score the export's standardized features and interaction terms."""
    z = {}
    for key, center in model["center"].items():
        value, scale = row.get(key), model["scale"].get(key)
        if finite(value) and finite(center) and finite(scale) and scale > 0:
            z[key] = clip((value - center) / scale, -8, 8)

    def part(key):
        return z.get(key, math.nan)

    score = model["intercept"]
    for column, coefficient in zip(model["columns"], model["coef"]):
        value = part(column)
        if " × " in column:
            left, right = column.split(" × ", 1)
            if right == "its change":
                value = .5 * part(left) * part("d_" + left)
            elif left.startswith("changes in "):
                value = .5 * part("d_" + left.removeprefix("changes in ")) * part("d_" + right)
            elif right.startswith("change in "):
                value = .5 * part(left) * part("d_" + right.removeprefix("change in "))
        if finite(value):
            score += value * coefficient
    return score


def load_pack(path=DATA_PATH):
    """Read the same JSON used by the browser and verify its saved replay cases."""
    with Path(path).open(encoding="utf-8") as handle:
        pack = json.load(handle)
    model = pack.get("model") or {}
    if (
        pack.get("format") != "hitter-what-if-v1"
        or not isinstance(pack.get("metrics"), list)
        or len(pack["metrics"]) != 26
        or not isinstance(pack.get("rows"), list) or not pack["rows"]
        or not isinstance(pack.get("history"), list)
        or not pack.get("replay") or model.get("penalty") != 1
        or not isinstance(model.get("columns"), list)
        or not isinstance(model.get("coef"), list)
        or len(model["columns"]) != len(model["coef"])
    ):
        raise ValueError("Use the JSON generated by the companion export notebook.")
    rows = pack["rows"]
    if len({row.get("MLBAM_ID") for row in rows}) != len(rows) or any(
        not isinstance(row.get("Name"), str) or not finite(row.get("anchor")) for row in rows
    ):
        raise ValueError("Player IDs or anchors are invalid.")
    for row in pack["replay"]:
        score = predict(model, row)
        if not finite(row.get("expected_full")) or not finite(score) or abs(score - row["expected_full"]) > 1e-9:
            raise ValueError("Saved model replay failed. Re-export the model data.")
    return pack


def available(pack, player, side):
    profile = player.get("scenario_base") or {}
    metrics = {}
    for spec in pack["metrics"]:
        key = spec["key"]
        field = f"{key}_{side}" if spec["side"] else key
        value = profile.get(field)
        if value is None:
            value = player.get(field)
        metrics[key] = {**spec, "field": field, "value": value if finite(value) else None}
    return metrics


def _solve(matrix, rhs):
    n = len(rhs)
    for i in range(n):
        pivot = max(range(i, n), key=lambda j: abs(matrix[j][i]))
        matrix[i], matrix[pivot] = matrix[pivot], matrix[i]
        rhs[i], rhs[pivot] = rhs[pivot], rhs[i]
        for j in range(i + 1, n):
            factor = matrix[j][i] / matrix[i][i]
            for k in range(i, n):
                matrix[j][k] -= factor * matrix[i][k]
            rhs[j] -= factor * rhs[i]
    result = [0.0] * n
    for i in range(n - 1, -1, -1):
        residual = rhs[i]
        for j in range(i + 1, n):
            residual -= matrix[i][j] * result[j]
        result[i] = residual / matrix[i][i]
    return result


def _moments(values):
    mean = sum(values) / len(values)
    return mean, math.sqrt(sum((value - mean) ** 2 for value in values) / len(values))


def _quantile(values, probability):
    return sorted(values)[math.floor((len(values) - 1) * probability + .5)]


def _link(history, player, target, drivers):
    if not drivers:
        return 0, "No active edits", 0, 0
    target_delta = "d_" + target
    rows = [row for row in history if finite(row.get(target_delta)) and all(
        finite(row.get(field)) and finite(row.get("d_" + field)) for field, _ in drivers
    )]
    n = len(rows)
    years = len({row["year"] for row in rows})
    m = len(drivers)
    if n < max(100, 20 * m):
        return 0, "Too few matched pairs", n, years

    delta_columns = [[row["d_" + field] for row in rows] for field, _ in drivers]
    scales = [_moments(column)[1] for column in delta_columns]
    if any(scale < 1e-8 for scale in scales):
        return 0, "No historical variation", n, years
    levels = [_moments([row[field] for row in rows]) for field, _ in drivers]

    def context(value, j):
        mean, sd = levels[j]
        return clip((value - mean) / max(sd, 1e-8), -3, 3)

    q = [edit / scales[j] for j, (_, edit) in enumerate(drivers)]
    outside = any(
        edit < _quantile(delta_columns[j], .01) or edit > _quantile(delta_columns[j], .99)
        for j, (_, edit) in enumerate(drivers)
    )
    if not outside:
        distances = sorted(
            math.sqrt(sum((q[j] - row["d_" + field] / scales[j]) ** 2
                          for j, (field, _) in enumerate(drivers)))
            for row in rows
        )
        outside = sum(distances[:10]) / 10 > 1.5 * math.sqrt(m)
    if outside:
        return 0, "Outside historical support", n, years

    dim = 1 + 3 * m
    matrix = [[0.0] * dim for _ in range(dim)]
    rhs = [0.0] * dim
    for row in rows:
        changes = [row["d_" + field] / scales[j] for j, (field, _) in enumerate(drivers)]
        levels_now = [context(row[field], j) for j, (field, _) in enumerate(drivers)]
        features = [1, *changes, *levels_now, *(a * b for a, b in zip(changes, levels_now))]
        for j, feature in enumerate(features):
            rhs[j] += feature * row[target_delta]
            for k in range(j + 1):
                matrix[j][k] += feature * features[k]
    penalty = 200 if SHORT_HISTORY.match(target) or any(SHORT_HISTORY.match(f) for f, _ in drivers) else 100
    for j in range(dim):
        if j:
            matrix[j][j] += penalty
        for k in range(j):
            matrix[k][j] = matrix[j][k]
    coefficients = _solve(matrix, rhs)
    raw = sum(
        value * (coefficients[1+j] + coefficients[1+2*m+j] * context(player.get(drivers[j][0]) or 0, j))
        for j, value in enumerate(q)
    )
    y = [row[target_delta] for row in rows]
    effect = clip(raw * n / (n + 120), min(0, _quantile(y, .02)), max(0, _quantile(y, .98)))
    if abs(effect) < .000005:
        status = "Near-zero fitted response"
    elif years < 3:
        status = f"Limited history · {years} transitions"
    else:
        status = "Estimated from history"
    return effect, status, n, years


def _shares(values, group, locks):
    if not all(finite(values.get(key)) for key in group):
        return
    free = [key for key in group if key not in locks]
    remainder = 100 - sum(values[key] for key in group if key in locks)
    if not -1e-7 <= remainder <= 100 * len(free) + 1e-7:
        raise ValueError("Locked values cannot balance the shares to 100%. Unlock or revise an edit.")
    if not free:
        return
    lo, hi = -201, 201
    for _ in range(50):
        mid = (lo + hi) / 2
        if sum(clip(values[key] + mid, 0, 100) for key in free) < remainder:
            lo = mid
        else:
            hi = mid
    for key in free:
        values[key] = clip(values[key] + (lo + hi) / 2, 0, 100)


def _share_range(values, group, key, locks):
    if key in locks or not all(finite(values.get(k)) for k in group):
        return values[key], values[key]
    others = [k for k in group if k != key]
    maximum = clip(100 - sum(values[k] for k in others if k in locks), 0, 100)
    return (maximum if all(k in locks for k in others) else 0), maximum


def _reconcile_pulled_air(values, locks):
    air_key, pull_key, gb_key = "pull_air_pp", "pull_pp", "groundball"
    air, pull, gb = (values.get(k) for k in (air_key, pull_key, gb_key))
    if not finite(air):
        return
    message = ("Locked GB%, Pull%, and Pull AIR% values cannot form a valid batted-ball profile. "
               "Revise or unlock an edit.")
    tol = 1e-7
    if air_key in locks:
        pull_lo, pull_hi = _share_range(values, SPRAY, pull_key, locks) if finite(pull) else (0, 100)
        if pull_hi + tol < air:
            raise ValueError(message)
        if finite(gb):
            gb_lo, gb_hi = _share_range(values, SHAPE, gb_key, locks)
            lo, hi = max(gb_lo, pull_lo - air, 0), min(gb_hi, 100 - air)
            if lo > hi + tol:
                raise ValueError(message)
            adjusted_gb = gb if gb_key in locks else clip(gb, lo, max(lo, hi))
            if abs(adjusted_gb - gb) > 1e-9:
                values[gb_key] = adjusted_gb
                _shares(values, SHAPE, locks | {gb_key})
            gb = adjusted_gb
        if finite(pull) and pull_key not in locks:
            lo, hi = max(pull_lo, air), min(pull_hi, gb + air if finite(gb) else 100)
            if lo > hi + tol:
                raise ValueError(message)
            adjusted_pull = clip(pull, lo, max(lo, hi))
            if abs(adjusted_pull - pull) > 1e-9:
                values[pull_key] = adjusted_pull
                _shares(values, SPRAY, locks | {pull_key})
    pull, gb = values.get(pull_key), values.get(gb_key)
    lo = max(0, pull - gb) if finite(pull) and finite(gb) else 0
    hi = min(pull if finite(pull) else 100, 100 - gb if finite(gb) else 100)
    if air_key not in locks:
        values[air_key] = clip(air, lo, hi)
    elif not lo - tol <= air <= hi + tol:
        raise ValueError(message)


def _reconcile(proposed, locks, touched):
    out = proposed.copy()
    if touched.intersection(SHAPE):
        air = SHAPE[1:]
        free = sum(key not in locks for key in air)
        rest = 100 - out["groundball"] - sum(out[k] for k in air if k in locks)
        keep = locks | {"groundball"} if -1e-8 <= rest <= 100 * free + 1e-8 else locks
        _shares(out, SHAPE, keep)
    spray_locks = locks | {"spray_other_pp"}
    if touched.intersection(SPRAY):
        _shares(out, SPRAY, spray_locks)
    if touched.intersection((*SHAPE, *SPRAY, "pull_air_pp")):
        _reconcile_pulled_air(out, spray_locks)
    if touched.intersection(("barrel", "hard_hit")) and out.get("barrel", 0) > out.get("hard_hit", math.inf):
        if {"barrel", "hard_hit"} <= locks:
            raise ValueError("Barrel% cannot exceed hard-hit%. Revise one locked value.")
        if "barrel" in locks:
            out["hard_hit"] = out["barrel"]
        elif "hard_hit" in locks:
            out["barrel"] = out["hard_hit"]
        else:
            out["barrel"] = out["hard_hit"] = (out["barrel"] + out["hard_hit"]) / 2
    return out


def default_side(pack, player):
    """Choose the side with more recorded metrics, matching the app."""
    def count(side):
        return sum(bool(spec["side"]) and finite(player.get(f"{spec['key']}_{side}"))
                   for spec in pack["metrics"])
    return "L" if count("L") > count("R") else "R"


def simulate(pack, player, edits=None, *, side=None, mode="linked"):
    """Calculate a scenario; rate edits are percentage points, EV edits are mph."""
    side = default_side(pack, player) if side is None else side
    if side not in ("L", "R") or mode not in ("manual", "linked"):
        raise ValueError("Choose side L or R and mode manual or linked.")
    edits = edits or {}
    info = available(pack, player, side)
    base = {key: spec["value"] for key, spec in info.items() if spec["value"] is not None}
    other = "spray_other_pp"
    if finite(player.get(other)):
        base[other] = player[other]
    locks = set(edits)
    beyond, thin, drivers = [], [], []
    history = pack["history"]
    for key, edit in edits.items():
        spec = info.get(key)
        if spec is None or key not in base or not finite(edit) or not (
            spec["min"] - 1e-9 <= base[key] + edit <= spec["max"] + 1e-9
        ):
            raise ValueError(f"Invalid change for {spec['label'] if spec else key}.")
        if abs(edit) > 1e-9:
            field = spec["field"]
            drivers.append((field, edit))
            hist = [r["d_" + field] for r in history if finite(r.get("d_" + field))]
            observed = player.get(field, math.nan)
            total = base[key] + edit - (0 if observed is None else observed)
            if len(hist) < 100:
                thin.append(spec["label"])
            elif finite(total) and not _quantile(hist, .01) <= total <= _quantile(hist, .99):
                beyond.append(spec["label"])

    manual, linked, proposed = {}, {}, {}
    for key, value in base.items():
        manual[key] = value + edits.get(key, 0)
        if mode == "linked" and key not in locks and key != other:
            linked[key] = _link(history, player, info[key]["field"], drivers)
        else:
            linked[key] = (0, "Locked by you" if key in locks else "Held fixed", 0, 0)
        proposed[key] = value if key == other else clip(
            manual[key] + linked[key][0], info[key]["min"], info[key]["max"]
        )
    touched = {key for key in base if abs(proposed[key] - base[key]) > 1e-9}
    final = _reconcile(proposed, locks, touched)
    model = pack["model"]
    zeros = {"d_" + key: 0 for key in model["fields"] if finite(player.get(key))}
    starting, ending = {**player, **zeros}, {**player, **zeros}
    details = []
    for key, spec in info.items():
        field = spec["field"]
        if finite(final.get(key)) and finite(player.get(field)):
            starting["d_" + field] = base[key] - player[field]
            ending["d_" + field] = final[key] - player[field]
        detail = {
            "key": key, "base": spec["value"], "edit": edits.get(key, 0),
            "linked": proposed[key] - manual[key] if key in base else None,
            "rule": final[key] - proposed[key] if key in base else None,
        }
        if key in linked:
            _, detail["status"], detail["n"], detail["years"] = linked[key]
            detail["final"] = final[key]
        else:
            detail["status"] = "Missing player measurement"
        details.append(detail)
    effect = predict(model, ending) - predict(model, starting)
    return {"effect": effect, "woba": player["anchor"] + effect, "details": details,
            "beyond": beyond, "thin": thin,
            "unsupported": sum(row["status"] == "Outside historical support" for row in details)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("hitter", help="Full player name (case insensitive)")
    parser.add_argument("--edit", action="append", default=[], metavar="METRIC=CHANGE")
    parser.add_argument("--side", choices=("L", "R"), help="Defaults to the side with more recorded metrics")
    parser.add_argument("--mode", choices=("manual", "linked"), default="linked")
    parser.add_argument("--data", type=Path, default=DATA_PATH)
    args = parser.parse_args()
    try:
        pack = load_pack(args.data)
        player = next((p for p in pack["rows"] if p["Name"].casefold() == args.hitter.casefold()), None)
        if player is None:
            raise ValueError(f"Hitter not found: {args.hitter}")
        edits = {}
        for token in args.edit:
            key, sep, amount = token.partition("=")
            if not sep or not key:
                raise ValueError(f"Expected METRIC=CHANGE, got {token!r}")
            edits[key] = float(amount)
        print(json.dumps(simulate(pack, player, edits, side=args.side, mode=args.mode),
                         indent=2, ensure_ascii=True, allow_nan=False))
    except (OSError, ValueError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()

"use strict";
const WobaEngine=(()=>{
  const finite=Number.isFinite;
  const clip=(x,a,b)=>Math.max(a,Math.min(b,x));
  const shape=['groundball','cache_ld_pp','cache_fb_pp','cache_pu_pp'];
  const spray=['pull_pp','center_pp','oppo_pp','spray_other_pp'];
  const short=/^(bat_speed|swing_length|attack_angle|swing_tilt|depth_in_box|off_plate|feet_apart|stance_angle)/;

  function predict(d,row){
    const z={};
    for(const k of Object.keys(d.center))z[k]=finite(row[k])&&finite(d.scale[k])&&d.scale[k]>0&&finite(d.center[k])?clip((row[k]-d.center[k])/d.scale[k],-8,8):NaN;
    let y=d.intercept;
    d.columns.forEach((c,i)=>{
      let x=z[c];
      if(c.includes(' × ')){
        const [a,b]=c.split(' × ');
        if(b==='its change')x=.5*z[a]*z['d_'+a];
        else if(a.startsWith('changes in '))x=.5*z['d_'+a.slice(11)]*z['d_'+b];
        else if(b.startsWith('change in '))x=.5*z[a]*z['d_'+b.slice(10)];
      }
      if(finite(x))y+=x*d.coef[i];
    });
    return y;
  }

  function parsePack(d){
    if(d?.format!=='hitter-what-if-v1'||!Array.isArray(d.metrics)||!Array.isArray(d.rows)||!Array.isArray(d.history)||!d.rows.length||d.metrics.length!==26||!d.model||!d.replay?.length||
    !Array.isArray(d.model.columns)||d.model.columns.length!==d.model.coef?.length||d.model.penalty!==1)throw Error('Use the JSON generated by the companion export notebook.');
    if(new Set(d.rows.map(r=>r.MLBAM_ID)).size!==d.rows.length||d.rows.some(r=>typeof r.Name!=='string'||!finite(r.anchor)))throw Error('Player IDs or anchors are invalid.');
    if(d.replay.some(row=>!finite(row.expected_full)||Math.abs(predict(d.model,row)-row.expected_full)>1e-9||!finite(predict(d.model,row))))throw Error('Saved model replay failed. Re-export the model data.');
    return d;
  }

  function available(d,p,side){
    const metrics={};
    for(const m of d.metrics){
      const k=m.side?m.key+'_'+side:m.key;
      const v=p.scenario_base?.[k] ?? p[k];
      metrics[m.key]={...m,field:k,value:finite(v)?v:null};
    }
    return metrics;
  }

  function solve(G,b){
    const n=b.length;
    for(let i=0;i<n;i++){
      let piv=i;
      for(let j=i+1;j<n;j++)if(Math.abs(G[j][i])>Math.abs(G[piv][i]))piv=j;
      if(piv!==i){[G[i],G[piv]]=[G[piv],G[i]];[b[i],b[piv]]=[b[piv],b[i]];}
      for(let j=i+1;j<n;j++){
        const f=G[j][i]/G[i][i];
        for(let k=i;k<n;k++)G[j][k]-=f*G[i][k];
        b[j]-=f*b[i];
      }
    }
    const x=Array(n).fill(0);
    for(let i=n-1;i>=0;i--){
      let s=b[i];for(let j=i+1;j<n;j++)s-=G[i][j]*x[j];x[i]=s/G[i][i];
    }
    return x;
  }

  function moments(values){
    const mean=values.reduce((a,b)=>a+b,0)/values.length;
    return [mean,Math.sqrt(values.reduce((s,v)=>s+(v-mean)**2,0)/values.length)];
  }

  function quant(values,p){const x=[...values].sort((a,b)=>a-b);return x[Math.round((x.length-1)*p)];}

  function link(d,prior,target,drivers){
    if(!drivers.length)return {d:0,status:'No active edits',n:0,years:0};
    const rows=d.history.filter(r=>finite(r['d_'+target])&&drivers.every(q=>finite(r[q.k])&&finite(r['d_'+q.k])));
    const n=rows.length,years=new Set(rows.map(r=>r.year)).size;
    if(n<Math.max(100,20*drivers.length))return {d:0,status:'Too few matched pairs',n,years};
    const ds=drivers.map(q=>rows.map(r=>r['d_'+q.k]));
    const levels=drivers.map(q=>rows.map(r=>r[q.k]));
    const scale=ds.map(v=>moments(v)[1]);
    if(scale.some(s=>s<1e-8))return {d:0,status:'No historical variation',n,years};
    const lx=levels.map(moments);
    const ctx=(v,j)=>clip((v-lx[j][0])/Math.max(lx[j][1],1e-8),-3,3);
    const q=drivers.map((v,j)=>v.d/scale[j]);
    const outer=drivers.some((v,j)=>v.d<quant(ds[j],.01)||v.d>quant(ds[j],.99));
    const near=rows.map(r=>Math.sqrt(drivers.reduce((s,v,j)=>s+(q[j]-r['d_'+v.k]/scale[j])**2,0))).sort((a,b)=>a-b);
    const distant=near.slice(0,10).reduce((a,b)=>a+b,0)/10>1.5*Math.sqrt(drivers.length);
    if(outer||distant)return {d:0,status:'Outside historical support',n,years};
    const m=drivers.length,dim=1+3*m,G=Array.from({length:dim},()=>Array(dim).fill(0)),rhs=Array(dim).fill(0);
    for(const r of rows){
      const a=drivers.map((v,j)=>r['d_'+v.k]/scale[j]),c=drivers.map((v,j)=>ctx(r[v.k],j));
      const x=[1,...a,...c,...a.map((v,j)=>v*c[j])], y=r['d_'+target];
      for(let j=0;j<dim;j++){
        rhs[j]+=x[j]*y;
        for(let k=0;k<=j;k++)G[j][k]+=x[j]*x[k];
      }
    }
    const penalty=(short.test(target)||drivers.some(v=>short.test(v.k)))?200:100;
    for(let j=0;j<dim;j++){
      if(j)G[j][j]+=penalty;
      for(let k=0;k<j;k++)G[k][j]=G[j][k];
    }
    const b=solve(G,rhs);
    const raw=q.reduce((s,v,j)=>s+v*(b[1+j]+b[1+2*m+j]*ctx(prior[drivers[j].k],j)),0);
    const response=raw*n/(n+120);
    const y=rows.map(r=>r['d_'+target]);

    const effect=clip(response,Math.min(0,quant(y,.02)),Math.max(0,quant(y,.98)));
    return {d:effect,status:Math.abs(effect)<.000005?'Near-zero fitted response':years<3?'Limited history · '+years+' transitions':'Estimated from history',n,years};
  }

  function shares(values, group, locks){
    if(!group.every(k=>finite(values[k])))return;
    const free=group.filter(k=>!locks.has(k));
    const fixed=group.filter(k=>locks.has(k)).reduce((s,k)=>s+values[k],0);
    const remainder=100-fixed;
    if(remainder< -1e-7||remainder>100*free.length+1e-7)throw Error('Locked values cannot balance the shares to 100%. Unlock or revise an edit.');
    if(!free.length)return;
    let lo=-201,hi=201;
    for(let i=0;i<50;i++){
      const mid=(hi+lo)/2;
      if(free.reduce((s,k)=>s+clip(values[k]+mid,0,100),0)<remainder)lo=mid;else hi=mid;
    }
    for(const k of free)values[k]=clip(values[k]+(lo+hi)/2,0,100);
  }

  function shareRange(values, group, key, locks){
    if(locks.has(key)||!group.every(k=>finite(values[k])))return [values[key],values[key]];
    const others=group.filter(k=>k!==key);
    const fixed=others.filter(k=>locks.has(k)).reduce((sum,k)=>sum+values[k],0);
    const max=clip(100-fixed,0,100);
    return [others.every(k=>locks.has(k))?max:0,max];
  }

  function reconcilePulledAir(out, locks){
    const airKey='pull_air_pp', pullKey='pull_pp', gbKey='groundball';
    const a=out[airKey], p=out[pullKey], g=out[gbKey];
    if(!finite(a))return;
    const error=()=>Error('Locked GB%, Pull%, and Pull AIR% values cannot form a valid batted-ball profile. Revise or unlock an edit.');
    const tolerance=1e-7;
    if(locks.has(airKey)){
      let ground=g;
      const [pullMin,pullMax]=finite(p)?shareRange(out,spray,pullKey,locks):[0,100];
      if(pullMax+tolerance<a)throw error();
      if(finite(g)){
        const [gbMin,gbMax]=shareRange(out,shape,gbKey,locks);
        const min=Math.max(gbMin,pullMin-a,0);
        const max=Math.min(gbMax,100-a);
        if(min>max+tolerance)throw error();
        ground=locks.has(gbKey)?g:clip(g,min,Math.max(min,max));
        if(Math.abs(ground-g)>1e-9){
          out[gbKey]=ground;
          shares(out,shape,new Set([...locks,gbKey]));
        }
      }
      if(finite(p)&&!locks.has(pullKey)){
        const min=Math.max(pullMin,a);
        const max=Math.min(pullMax,finite(ground)?ground+a:100);
        if(min>max+tolerance)throw error();
        const pull=clip(p,min,Math.max(min,max));
        if(Math.abs(pull-p)>1e-9){
          out[pullKey]=pull;
          shares(out,spray,new Set([...locks,pullKey]));
        }
      }
    }
    const low=finite(out[pullKey])&&finite(out[gbKey])?Math.max(0,out[pullKey]-out[gbKey]):0;
    const high=Math.min(finite(out[pullKey])?out[pullKey]:100,finite(out[gbKey])?100-out[gbKey]:100);
    if(locks.has(airKey)){
      if(a<low-tolerance||a>high+tolerance)throw error();
    }else{
      out[airKey]=clip(a,low,high);
    }
  }

  function reconcile(v,locks,touched){
    const out={...v};
    const touches=g=>g.some(k=>touched.has(k));
    if(touches(shape)){
      const keep=new Set(locks),air=shape.slice(1),n=air.filter(k=>!locks.has(k)).length;
      const rest=100-out.groundball-air.filter(k=>locks.has(k)).reduce((s,k)=>s+out[k],0);
      if(rest>=-1e-8&&rest<=100*n+1e-8)keep.add('groundball');
      shares(out,shape,keep);
    }
    const sprayLocks=new Set([...locks,'spray_other_pp']);
    if(touches(spray))shares(out,spray,sprayLocks);
    if(touches([...shape,...spray,'pull_air_pp']))reconcilePulledAir(out,sprayLocks);
    if(touches(['barrel','hard_hit'])&&out.barrel>out.hard_hit){
      if(locks.has('barrel')&&locks.has('hard_hit'))throw Error('Barrel% cannot exceed hard-hit%. Revise one locked value.');
      if(locks.has('barrel'))out.hard_hit=out.barrel;
      else if(locks.has('hard_hit'))out.barrel=out.hard_hit;
      else out.barrel=out.hard_hit=(out.barrel+out.hard_hit)/2;
    }
    return out;
  }

  function simulate(d,p,side,edits,mode){
    const info=available(d,p,side),base={},manual={},proposed={},linked={};
    for(const [k,m] of Object.entries(info))if(finite(m.value))base[k]=m.value;
    if(finite(p.spray_other_pp))base.spray_other_pp=p.spray_other_pp;
    const locks=new Set(Object.keys(edits));
    const beyond=[], thin=[];
    const drivers=[];
    for(const [k,v] of Object.entries(edits)){
      if(!info[k]||!finite(base[k])||!finite(v)||base[k]+v<info[k].min-1e-9||base[k]+v>info[k].max+1e-9)throw Error('Invalid change for '+(info[k]?.label||k)+'.');
      if(Math.abs(v)>1e-9){
        const field=info[k].field;
        drivers.push({k:field,d:v});
        const hist=d.history.map(r=>r['d_'+field]).filter(finite);
        const total=base[k]+v-p[field];
        if(hist.length>=100&&finite(total)&&(total<quant(hist,.01)||total>quant(hist,.99)))beyond.push(info[k].label);
        else if(hist.length<100)thin.push(info[k].label);
      }
    }
    for(const [k,v] of Object.entries(base)){
      manual[k]=v+(edits[k]||0);
      linked[k]=mode==='linked'&&!locks.has(k)&&k!=='spray_other_pp'?link(d,p,info[k].field,drivers):{d:0,status:locks.has(k)?'Locked by you':'Held fixed',n:0,years:0};
      proposed[k]=k==='spray_other_pp'?v:clip(manual[k]+linked[k].d,info[k].min,info[k].max);
    }
    const touched=new Set(Object.keys(base).filter(k=>Math.abs(proposed[k]-base[k])>1e-9));
    const final=reconcile(proposed,locks,touched);
    const x0={...p},x1={...p};
    for(const k of d.model.fields)if(finite(p[k]))x0['d_'+k]=x1['d_'+k]=0;
    for(const [k,m] of Object.entries(info))if(finite(final[k])&&finite(p[m.field])){
      x0['d_'+m.field]=base[k]-p[m.field];
      x1['d_'+m.field]=final[k]-p[m.field];
    }
    const effect=predict(d.model,x1)-predict(d.model,x0);
    const details=Object.values(info).map(m=>({key:m.key,base:m.value,edit:edits[m.key]||0,
        linked:finite(m.value)?proposed[m.key]-manual[m.key]:null,
        rule:finite(m.value)?final[m.key]-proposed[m.key]:null,final:final[m.key],
        ...(linked[m.key]?{n:linked[m.key].n,years:linked[m.key].years,status:linked[m.key].status}:{status:'Missing player measurement'})}));
    const unsupported=details.filter(x=>x.status==='Outside historical support').length;
    return {effect,woba:p.anchor+effect,details,beyond,thin,unsupported};
  }

  return {predict,parsePack,available,simulate};
})();
if(typeof module!=='undefined')module.exports=WobaEngine;
